import qrcode, sys
ADDR = "0x34260B953eC6e56e62121Aa3913db3ED89C69A2E"
qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
qr.add_data(ADDR); qr.make(fit=True)
m = qr.get_matrix(); n = len(m); q = 2  # quiet zone (modules)
size = n + 2*q
# one path, horizontal runs of dark modules per row
d = []
for y,row in enumerate(m):
    x = 0
    while x < n:
        if row[x]:
            s = x
            while x < n and row[x]: x += 1
            d.append(f"M{s+q},{y+q}h{x-s}v1h{-(x-s)}z")
        else: x += 1
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Fugueti Launcher: donation address QR code ({ADDR}). Generated by art/qr/gen_qr.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size*6}dp"
    android:height="{size*6}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}">
    <path android:fillColor="#FFFFFF" android:pathData="M0,0h{size}v{size}h-{size}z" />
    <path android:fillColor="#000000" android:pathData="{''.join(d)}" />
</vector>
'''
open(sys.argv[1], "w").write(xml)
print("modules", n, "version", qr.version)
